class DojoV3Historical:
    """
    Dojo v3: Historical data training manager.

    Trains on real market data using rainbow table schedule.
    """

    def __init__(
        self,
        schedule_path: str = 'training_schedule.json',
        checkpoint_dir: str = 'jax_ckpt_fast',
        model_size: str = 'small',
        db_path: str = 'trading_data.db',
        model_name: str = MODEL_NAME,
        model_version: str = MODEL_VERSION,
        epochs_per_block: int = 60,
    ):
        self.schedule_path = schedule_path
        self.checkpoint_dir = checkpoint_dir
        self.model_size = model_size
        self.db_path = db_path
        self.model_name = model_name
        self.model_version = model_version
        self.epochs_per_block = epochs_per_block

        self.schedule = self._load_schedule()
        self.benchmark_config = self._load_benchmark_config()

        # TASK_105: Filter periods to only those with available data
        self.db_max_date = self._get_db_max_date()
        raw_periods = self.schedule.get('periods', [])
        self.valid_periods = self._filter_valid_periods(raw_periods, self.db_max_date)
        logging.info(f"Valid periods: {len(self.valid_periods)} of {len(raw_periods)} "
                     f"(DB max: {self.db_max_date.strftime('%Y-%m-%d')})")

        # Flatten all runs from valid periods
        self.valid_runs = self._flatten_runs(self.valid_periods)
        logging.info(f"Valid runs: {len(self.valid_runs)} (all asset combinations)")

        os.makedirs(checkpoint_dir, exist_ok=True)
        os.makedirs('logs/benchmarks', exist_ok=True)

    def _load_schedule(self) -> Dict:
        """Load training schedule from JSON."""
        if not os.path.exists(self.schedule_path):
            raise FileNotFoundError(f"Schedule not found: {self.schedule_path}")

        with open(self.schedule_path) as f:
            schedule = json.load(f)

        logging.info(f"Loaded schedule: {schedule['summary']['total_epochs']} epochs, "
                     f"{schedule['summary']['total_training_years']} years")
        return schedule

    def _load_benchmark_config(self) -> Dict:
        """Load benchmark periods configuration."""
        config_path = PROJECT_ROOT / 'config' / 'benchmark_periods.json'
        if config_path.exists():
            with open(config_path) as f:
                return json.load(f)
        else:
            logging.warning(f"Benchmark config not found at {config_path}")
            return {}

    def _get_db_max_date(self) -> datetime:
        """
        TASK_105: Get the maximum timestamp available in the database.
        Used to filter out periods requesting future data.

        Checks config/dojo_override.json for 'db_effective_end_date' first,
        which overrides the MAX(timestamp) query (useful when DB has sparse future data).
        """
        # Check for config override first
        override_config = self._load_override_config()
        if 'db_effective_end_date' in override_config:
            try:
                override_date = override_config['db_effective_end_date']
                effective_end = datetime.strptime(override_date, '%Y-%m-%d')
                logging.info(f"Using db_effective_end_date override: {override_date}")
                return effective_end
            except Exception as e:
                logging.warning(f"Invalid db_effective_end_date format: {e}")

        # Fall back to DB query
        import sqlite3
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            cursor.execute("SELECT MAX(timestamp) FROM ohlcv")
            max_ts = cursor.fetchone()[0]
            conn.close()

            if max_ts:
                return datetime.fromtimestamp(max_ts)
            else:
                logging.warning("Could not get max timestamp from DB, using now()")
                return datetime.now()
        except Exception as e:
            logging.warning(f"Error getting DB max date: {e}, using now()")
            return datetime.now()

    def _filter_valid_periods(self, periods: List[Dict], db_max_date: datetime) -> List[Dict]:
        """
        TASK_105: Filter periods to only include those with data available.
        Removes periods where end_date > db_max_date (period extends beyond available data).
        """
        valid = []
        skipped = 0

        for period in periods:
            # Parse end date from period
            end_date_str = period.get('end_date', '')
            if not end_date_str:
                # Try 'end' field (timestamp format)
                end_ts = period.get('end', 0)
                period_end = datetime.fromtimestamp(end_ts)
            else:
                period_end = datetime.fromisoformat(end_date_str[:10])

            if period_end <= db_max_date:
                valid.append(period)
            else:
                skipped += 1
                logging.info(f"  Skipping period ending {period_end.strftime('%Y-%m-%d')} (beyond DB max)")

        if skipped > 0:
            logging.warning(f"Filtered out {skipped} periods beyond DB max date ({db_max_date.strftime('%Y-%m-%d')})")

        return valid

    def _flatten_runs(self, periods: List[Dict]) -> List[Dict]:
        """
        Flatten periods into individual runs.
        Each period may have multiple training_runs with different asset combinations.
        Returns list of {start_date, end_date, assets, run_id, period_idx}.
        """
        all_runs = []
        N_ASSETS = 64

        for period_idx, period in enumerate(periods):
            # Get period dates
            if 'start_date' in period:
                start_date = period['start_date'][:10]
                end_date = period['end_date'][:10]
            else:
                start_date = datetime.fromtimestamp(period['start']).strftime('%Y-%m-%d')
                end_date = datetime.fromtimestamp(period['end']).strftime('%Y-%m-%d')

            duration = period.get('duration_days', '?')
            runs = period.get('training_runs', [])

            if not runs:
                # Fallback: create single run from available_assets
                assets = period.get('available_assets', [])
                if assets:
                    runs = [{'run_id': 1, 'assets': assets}]

            for run in runs:
                assets = run.get('assets', [])
                if not assets:
                    continue

                # Pad to 64 assets
                if len(assets) < N_ASSETS:
                    while len(assets) < N_ASSETS:
                        assets = assets + assets[:N_ASSETS - len(assets)]
                    assets = assets[:N_ASSETS]
                elif len(assets) > N_ASSETS:
                    assets = assets[:N_ASSETS]

                all_runs.append({
                    'start_date': start_date,
                    'end_date': end_date,
                    'duration_days': duration,
                    'assets': assets,
                    'run_id': run.get('run_id', 1),
                    'period_idx': period_idx,
                })

        return all_runs

    def _load_override_config(self) -> Dict:
        """
        Load hot config overrides from config/dojo_override.json.

        Example file:
        {
            "sims": 32,
            "parallel-envs": 20,
            "epsilon-greedy": 0.1
        }
        """
        config_path = PROJECT_ROOT / OVERRIDE_CONFIG_PATH
        if config_path.exists():
            try:
                with open(config_path) as f:
                    overrides = json.load(f)
                if overrides:
                    logging.info(f"  [HOT CONFIG] Loaded overrides: {overrides}")
                return overrides
            except Exception as e:
                logging.warning(f"  [HOT CONFIG] Error loading {config_path}: {e}")
                return {}
        return {}

    def _apply_overrides(self, cmd: List[str], overrides: Dict) -> List[str]:
        """Apply override config to command, replacing existing flags."""
        if not overrides:
            return cmd

        # Convert to list we can modify
        cmd = list(cmd)

        # Keys that are handled elsewhere or are comments
        SKIP_KEYS = {'db_effective_end_date'}

        for flag_name, value in overrides.items():
            # Skip comment fields (start with _) and known non-flag keys
            if flag_name.startswith('_') or flag_name in SKIP_KEYS:
                continue

            if flag_name not in OVERRIDABLE_FLAGS:
                logging.warning(f"  [HOT CONFIG] Unknown flag '{flag_name}', skipping")
                continue

            flag = f'--{flag_name}'
            flag_type = OVERRIDABLE_FLAGS[flag_name]

            # Handle bool flags (no value, just presence/absence)
            if flag_type == bool:
                if value:
                    if flag not in cmd:
                        cmd.append(flag)
                        logging.info(f"  [HOT CONFIG] Enabled: {flag}")
                else:
                    if flag in cmd:
                        cmd.remove(flag)
                        logging.info(f"  [HOT CONFIG] Disabled: {flag}")
                continue

            # Find and replace existing flag, or append
            found = False
            for i, arg in enumerate(cmd):
                if arg == flag and i + 1 < len(cmd):
                    cmd[i + 1] = str(value)
                    found = True
                    logging.info(f"  [HOT CONFIG] Override: {flag} = {value}")
                    break

            if not found:
                # Append new flag
                cmd.extend([flag, str(value)])
                logging.info(f"  [HOT CONFIG] Added: {flag} = {value}")

        return cmd

    def run_training(
        self,
        start_checkpoint: Optional[str] = None,
        start_block: int = 1,
        max_blocks: Optional[int] = None,
    ):
        """
        Run historical training through rainbow table.

        Args:
            start_checkpoint: Initial checkpoint (default: poppy_v2_synthetic_complete)
            start_block: Starting block number (1-based, for H01, H02, ...)
            max_blocks: Maximum blocks to train (None = all)
        """
        logging.info("=" * 70)
        logging.info("DOJO V3 - HISTORICAL DATA TRAINING")
        logging.info("=" * 70)
        logging.info(f"Model: {self.model_name} v{self.model_version}")
        logging.info(f"Schedule: {self.schedule_path}")
        logging.info(f"Epochs per block: {self.epochs_per_block}")
        logging.info(f"Total periods: {self.schedule['summary']['total_periods']}")
        logging.info(f"Total runs: {self.schedule['summary']['total_unique_runs']}")
        logging.info(f"Total epochs: {self.schedule['summary']['total_epochs']}")
        logging.info("=" * 70)

        # Default checkpoint
        if start_checkpoint is None:
            start_checkpoint = os.path.join(
                self.checkpoint_dir,
                f'{self.model_name}_v{self.model_version}_synthetic_complete'
            )
            if not os.path.exists(start_checkpoint):
                # Fallback to L14 phase C
                start_checkpoint = os.path.join(
                    self.checkpoint_dir,
                    f'{self.model_name}_v{self.model_version}_L14_phase_C'
                )

        if not os.path.exists(start_checkpoint):
            logging.error(f"Checkpoint not found: {start_checkpoint}")
            return False

        logging.info(f"Starting from: {start_checkpoint}")

        checkpoint = start_checkpoint
        total_epochs_trained = 0
        current_block = start_block

        # Iterate through periods and runs
        for period in self.schedule['periods']:
            period_start = period['start_date']
            period_end = period['end_date']
            duration = period['duration_days']
            # Always 60 epochs per run (one block), regardless of period duration
            # Data will loop if period < 60*15 days
            epochs_per_run = self.epochs_per_block  # 60

            logging.info("")
            logging.info(f"PERIOD: {period_start} → {period_end} ({duration} days)")
            logging.info(f"  Assets: {period['asset_count']} persistent")
            logging.info(f"  Runs: {len(period['training_runs'])}")
            logging.info(f"  Epochs/run: {epochs_per_run}")

            for run in period['training_runs']:
                run_id = run['run_id']
                assets = run['assets']
                overlap = run['overlap_with_previous']

                # Pad to 64 assets if needed (model trained on 64 assets)
                N_ASSETS = 64
                if len(assets) < N_ASSETS:
                    # Repeat assets cyclically to fill to 64
                    original_count = len(assets)
                    while len(assets) < N_ASSETS:
                        assets = assets + assets[:N_ASSETS - len(assets)]
                    assets = assets[:N_ASSETS]
                    logging.info(f"  RUN {run_id}: {original_count} assets padded to {N_ASSETS} (overlap: {overlap:.0%})")
                elif len(assets) > N_ASSETS:
                    # Truncate to 64
                    assets = assets[:N_ASSETS]
                    logging.info(f"  RUN {run_id}: truncated to {N_ASSETS} assets (overlap: {overlap:.0%})")
                else:
                    logging.info(f"  RUN {run_id}: {len(assets)} assets (overlap: {overlap:.0%})")

                # Train this run
                checkpoint, epochs_this_run = self._train_run(
                    checkpoint=checkpoint,
                    start_date=period_start,
                    end_date=period_end,
                    assets=assets,
                    epochs=epochs_per_run,
                    run_name=f"period_{period_start[:10]}_run{run_id}",
                )

                if checkpoint is None:
                    logging.error("Training failed!")
                    return False

                total_epochs_trained += epochs_this_run

                # Check if we've completed a block
                if total_epochs_trained >= current_block * self.epochs_per_block:
                    block_name = f"H{current_block:02d}"
                    logging.info("")
                    logging.info(f">>> BLOCK {block_name} COMPLETE ({total_epochs_trained} epochs)")

                    # Save block checkpoint
                    block_checkpoint = os.path.join(
                        self.checkpoint_dir,
                        f'{self.model_name}_v{self.model_version}_{block_name}'
                    )
                    self._copy_checkpoint(checkpoint, block_checkpoint)

                    # Run benchmark
                    logging.info(f">>> BENCHMARK: Block {block_name}")
                    benchmark_results = self._run_benchmark(block_checkpoint, block_name)
                    self._save_benchmark_results(block_name, benchmark_results)

                    current_block += 1

                    # Check max blocks
                    if max_blocks and current_block > max_blocks:
                        logging.info(f"Reached max blocks ({max_blocks}), stopping")
                        break

            # Check max blocks (outer loop)
            if max_blocks and current_block > max_blocks:
                break

        logging.info("")
        logging.info("=" * 70)
        logging.info("HISTORICAL TRAINING COMPLETE!")
        logging.info(f"Total epochs: {total_epochs_trained}")
        logging.info(f"Blocks completed: {current_block - 1}")
        logging.info("=" * 70)

        return True

    def run_training_stratified(
        self,
        start_checkpoint: Optional[str] = None,
        start_block: int = 1,
        max_blocks: Optional[int] = None,
        periods_per_batch: int = 4,
        epochs_per_period: int = 15,
        loop_mode: bool = False,
    ):
        """
        TASK_064: Stratified training - cycle through periods to prevent forgetting.
        TASK_105: Added loop_mode and valid period filtering.

        Instead of training all epochs on period 0, then all on period 1, etc.,
        this method cycles: 15 epochs on P0, 15 on P1, 15 on P2, 15 on P3, repeat.

        Args:
            start_checkpoint: Initial checkpoint
            start_block: Starting block number
            max_blocks: Maximum blocks to train
            periods_per_batch: Number of periods to batch (default: 4)
            epochs_per_period: Epochs per period before switching (default: 15)
            loop_mode: If True, cycle forever until Ctrl+C. If False, one-shot through all periods.
        """
        mode_str = "INFINITE LOOP (Ctrl+C to stop)" if loop_mode else "ONE-SHOT"
        logging.info("=" * 70)
        logging.info(f"DOJO V3 - STRATIFIED HISTORICAL TRAINING ({mode_str})")
        logging.info("=" * 70)
        logging.info(f"Model: {self.model_name} v{self.model_version}")
        logging.info(f"Periods per batch: {periods_per_batch}")
        logging.info(f"Epochs per period: {epochs_per_period}")
        logging.info(f"Epochs per block: {periods_per_batch * epochs_per_period}")
        logging.info(f"Valid periods: {len(self.valid_periods)}, Valid runs: {len(self.valid_runs)}")
        logging.info("=" * 70)

        # Default checkpoint
        if start_checkpoint is None:
            start_checkpoint = os.path.join(
                self.checkpoint_dir,
                f'{self.model_name}_v{self.model_version}_synthetic_complete'
            )
            if not os.path.exists(start_checkpoint):
                start_checkpoint = os.path.join(
                    self.checkpoint_dir,
                    f'{self.model_name}_v{self.model_version}_L14_phase_C'
                )

        if not os.path.exists(start_checkpoint):
            logging.error(f"Checkpoint not found: {start_checkpoint}")
            return False

        logging.info(f"Starting from: {start_checkpoint}")

        if not self.valid_runs:
            logging.error("No valid runs available! Check database data range.")
            return False

        checkpoint = start_checkpoint
        total_epochs_trained = 0
        current_block = start_block

        # TASK_105: Use valid_runs with cursor-based iteration (all runs, not just periods)
        n_runs = len(self.valid_runs)
        cursor = 0
        batch_num = 0

        while True:
            # Build batch from cursor position (now iterating through runs, not periods)
            batch_runs = []
            for _ in range(periods_per_batch):
                if cursor >= n_runs:
                    if loop_mode:
                        cursor = 0  # Wraparound
                        logging.info(">>> Wrapping around to run 0")
                    else:
                        break  # One-shot: stop collecting

                batch_runs.append(self.valid_runs[cursor])
                cursor += 1

            # Exit if no runs collected (one-shot mode exhausted)
            if not batch_runs:
                logging.info("All runs exhausted (one-shot mode)")
                break

            batch_num += 1
            actual_batch_size = len(batch_runs)

            logging.info("")
            logging.info(f"BATCH {batch_num}: {actual_batch_size} runs (cursor {cursor}/{n_runs})")
            for i, run in enumerate(batch_runs):
                start_str = run['start_date']
                end_str = run['end_date']
                duration = run.get('duration_days', '?')
                run_id = run.get('run_id', 1)
                period_idx = run.get('period_idx', '?')
                logging.info(f"  R{i}: P{period_idx}/Run{run_id} {start_str} → {end_str} ({duration} days)")

            # TASK_064: Single-process stratified training (no subprocess overhead)
            # Generate periods JSON file for train_jax_fast.py --periods-file
            epochs_this_batch = actual_batch_size * epochs_per_period
            periods_for_json = []

            for run in batch_runs:
                # Runs are already flattened with pre-padded assets
                periods_for_json.append({
                    'start_date': run['start_date'],
                    'end_date': run['end_date'],
                    'assets': run['assets'],
                })

            if not periods_for_json:
                logging.warning(f"  No valid runs in batch {batch_num}, skipping")
                continue

            # Write periods file
            batch_name = f"batch{batch_num}"
            periods_file = f'/tmp/dojo_periods_{batch_name}.json'
            with open(periods_file, 'w') as f:
                json.dump({'periods': periods_for_json}, f, indent=2)

            logging.info(f"  Single-process training: {epochs_this_batch} epochs across {len(periods_for_json)} periods")

            # Run training in single process with period cycling
            checkpoint, epochs_trained = self._train_stratified_batch(
                checkpoint=checkpoint,
                periods_file=periods_file,
                epochs=epochs_this_batch,
                run_name=batch_name,
            )

            if checkpoint is None:
                logging.error("Training failed!")
                return False

            total_epochs_trained += epochs_trained

            # Block checkpoint after batch
            block_name = f"H{current_block:02d}"
            logging.info("")
            logging.info(f">>> BLOCK {block_name} COMPLETE ({total_epochs_trained} epochs)")

            block_checkpoint = os.path.join(
                self.checkpoint_dir,
                f'{self.model_name}_v{self.model_version}_{block_name}'
            )
            self._copy_checkpoint(checkpoint, block_checkpoint)

            # Benchmark
            logging.info(f">>> BENCHMARK: Block {block_name}")
            benchmark_results = self._run_benchmark(block_checkpoint, block_name)
            self._save_benchmark_results(block_name, benchmark_results)

            current_block += 1

            if max_blocks and current_block > max_blocks:
                logging.info(f"Reached max blocks ({max_blocks}), stopping")
                break

        logging.info("")
        logging.info("=" * 70)
        logging.info("STRATIFIED HISTORICAL TRAINING COMPLETE!")
        logging.info(f"Total epochs: {total_epochs_trained}")
        logging.info(f"Blocks completed: {current_block - 1}")
        logging.info("=" * 70)

        return True

    def _train_run(
        self,
        checkpoint: str,
        start_date: str,
        end_date: str,
        assets: List[str],
        epochs: int,
        run_name: str,
    ) -> tuple:
        """
        Train on a single run (period + asset combination).

        Returns:
            (checkpoint_path, epochs_trained)
        """
        experiment_name = f'{self.model_name}_v{self.model_version}_historical_{run_name}'

        # Write assets to temp file for --assets-file flag
        assets_file = f'/tmp/dojo_assets_{run_name}.json'
        with open(assets_file, 'w') as f:
            json.dump(assets, f)

        # Convert ISO dates to YYYY-MM-DD
        start_date_short = start_date[:10]
        end_date_short = end_date[:10]

        # Build command
        cmd = [
            'python', 'train_jax_fast.py',
            '--db-path', self.db_path,
            '--start-date', start_date_short,
            '--end-date', end_date_short,
            '--epochs', str(epochs),
            '--steps', '1440',            # 1 day of 1-min candles per step batch
            '--assets-file', assets_file,
            '--name', experiment_name,
            '--model-size', self.model_size,
            '--load-checkpoint', checkpoint,
        ]

        # Add historical flags
        cmd.extend(HISTORICAL_FLAGS)

        # Load and apply hot config overrides
        overrides = self._load_override_config()
        cmd = self._apply_overrides(cmd, overrides)

        # Run training
        start_time = time.time()
        try:
            result = subprocess.run(
                cmd,
                cwd=str(PROJECT_ROOT),
                capture_output=False,
                timeout=3600 * 4,  # 4 hour timeout per run
            )

            elapsed = time.time() - start_time
            logging.info(f"    Run completed in {elapsed/60:.1f} minutes")

            if result.returncode != 0:
                logging.error(f"Training failed with return code {result.returncode}")
                return None, 0

        except subprocess.TimeoutExpired:
            logging.error("Training timed out!")
            return None, 0
        except Exception as e:
            logging.error(f"Training error: {e}")
            return None, 0

        # Return checkpoint path
        new_checkpoint = os.path.join(self.checkpoint_dir, experiment_name)
        if os.path.exists(new_checkpoint):
            return new_checkpoint, epochs
        else:
            logging.warning(f"Checkpoint not found at {new_checkpoint}")
            return checkpoint, epochs

    def _train_stratified_batch(
        self,
        checkpoint: str,
        periods_file: str,
        epochs: int,
        run_name: str,
    ) -> tuple:
        """
        TASK_064: Train on multiple periods with single-process stratified cycling.

        Uses --periods-file to load all period data upfront, then cycles through
        them epoch-by-epoch without subprocess overhead.

        Returns:
            (checkpoint_path, epochs_trained)
        """
        experiment_name = f'{self.model_name}_v{self.model_version}_historical_{run_name}'

        # Build command - uses --periods-file instead of --start-date/--end-date
        cmd = [
            'python', 'train_jax_fast.py',
            '--db-path', self.db_path,
            '--periods-file', periods_file,
            '--epochs', str(epochs),
            '--steps', '1440',            # 1 day of 1-min candles per step batch
            '--name', experiment_name,
            '--model-size', self.model_size,
            '--load-checkpoint', checkpoint,
            '--smart-allocation',         # Required for period cycling
        ]

        # Add historical flags
        cmd.extend(HISTORICAL_FLAGS)

        # Load and apply hot config overrides
        overrides = self._load_override_config()
        cmd = self._apply_overrides(cmd, overrides)

        # Run training
        start_time = time.time()
        try:
            result = subprocess.run(
                cmd,
                cwd=str(PROJECT_ROOT),
                capture_output=False,
                timeout=3600 * 8,  # 8 hour timeout for full batch
            )

            elapsed = time.time() - start_time
            logging.info(f"    Batch completed in {elapsed/60:.1f} minutes")

            if result.returncode != 0:
                logging.error(f"Training failed with return code {result.returncode}")
                return None, 0

        except subprocess.TimeoutExpired:
            logging.error("Training timed out!")
            return None, 0
        except Exception as e:
            logging.error(f"Training error: {e}")
            return None, 0

        # Return checkpoint path
        new_checkpoint = os.path.join(self.checkpoint_dir, experiment_name)
        if os.path.exists(new_checkpoint):
            return new_checkpoint, epochs
        else:
            logging.warning(f"Checkpoint not found at {new_checkpoint}")
            return checkpoint, epochs

    def _copy_checkpoint(self, src: str, dst: str):
        """Copy checkpoint directory."""
        import shutil
        if os.path.exists(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
        logging.info(f"    Saved block checkpoint: {dst}")

    def _run_benchmark(self, checkpoint: str, block_name: str) -> Dict[str, Dict]:
        """Run benchmark on all periods."""
        results = {}

        if not self.benchmark_config:
            logging.warning("No benchmark config, skipping benchmark")
            return results

        periods = self.benchmark_config.get('periods', [])
        bench_cfg = self.benchmark_config.get('benchmark_config', {})

        epochs_per_period = bench_cfg.get('epochs_per_period', 7)
        steps = bench_cfg.get('steps_per_epoch', 1440)
        parallel_envs = bench_cfg.get('parallel_envs', 4)
        warmup_epochs = bench_cfg.get('warmup_epochs', 7)

        for period in periods:
            period_name = period['name']
            start_date = period['start_date']
            end_date = period['end_date']

            logging.info(f"    Benchmark: {period_name} ({start_date} to {end_date})")

            cmd = [
                'python', 'train_jax_fast.py',
                '--db-path', self.db_path,
                '--start-date', start_date,
                '--end-date', end_date,
                '--epochs', str(warmup_epochs + epochs_per_period),
                '--steps', str(steps),
                '--parallel-envs', str(parallel_envs),
                '--load-checkpoint', checkpoint,
                '--no-checkpoint',
                '--jax-env',
                '--bf16',
                '--model-size', self.model_size,
                '--name', f'{self.model_name}_benchmark_{block_name}_{period_name}',
                # Inference-critical flags
                '--popart-beta', '0.0001',
                '--use-gae', '--gae-lambda', '0.95',
                '--sims', '24',
                '--use-prediction-loss', '--use-student-t',
                '--prediction-loss-weight', '0.5',
                '--adaptive-entropy',
                '--entropy-coef', '0.2',
                '--entropy-hold-threshold', '0.55',
            ]

            try:
                result = subprocess.run(
                    cmd,
                    cwd=str(PROJECT_ROOT),
                    capture_output=True,
                    text=True,
                    timeout=1800,
                )

                output = result.stdout + result.stderr
                metrics = self._parse_benchmark_output(output)
                results[period_name] = metrics

                logging.info(f"      {period_name}: reward={metrics.get('reward', 0):.2f}, "
                             f"alpha={metrics.get('alpha', 0):.2f}%")

            except Exception as e:
                logging.error(f"      Benchmark {period_name} failed: {e}")
                results[period_name] = {'reward': 0, 'alpha': 0, 'error': str(e)}

        return results

    def _parse_benchmark_output(self, output: str) -> Dict:
        """Parse training output to extract benchmark metrics."""
        import re

        metrics = {
            'reward': 0.0,
            'alpha': 0.0,
            'market_return': 0.0,
            'entropy': 0.0,
            'hold_pct': 0.0,
            'total_loss': 0.0,
        }

        rewards = []
        alphas = []

        # Pattern: "Ep   50 | Reward:  +33.61 | α: +241.02% (Mkt: +9.7%)"
        # Note: Output uses "Ep" not "Epoch"
        epoch_pattern = r'Ep\s+(\d+)\s+\|\s+Reward:\s+([\+\-]?\d+\.?\d*)\s+\|\s+α:\s+([\+\-]?\d+\.?\d*)%'
        for match in re.findall(epoch_pattern, output):
            rewards.append(float(match[1]))
            alphas.append(float(match[2]))

        if rewards:
            metrics['reward'] = sum(rewards) / len(rewards)
            metrics['alpha'] = sum(alphas) / len(alphas)

        # HOLD percentage
        hold_pattern = r'HOLD:\s*(\d+\.?\d*)%'
        hold_matches = re.findall(hold_pattern, output)
        if hold_matches:
            metrics['hold_pct'] = float(hold_matches[-1])

        # Entropy
        entropy_pattern = r'Ent:\s*(\d+\.?\d*)'
        entropy_matches = re.findall(entropy_pattern, output)
        if entropy_matches:
            metrics['entropy'] = float(entropy_matches[-1])

        return metrics

    def _save_benchmark_results(self, block_name: str, results: Dict[str, Dict]):
        """Save benchmark results to CSV."""
        import csv

        filename = f'logs/benchmarks/{self.model_name}_v{self.model_version}_{block_name}_benchmark.csv'

        with open(filename, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['period', 'reward', 'alpha', 'market_return', 'hold_pct', 'entropy'])

            for period_name, metrics in results.items():
                writer.writerow([
                    period_name,
                    metrics.get('reward', 0),
                    metrics.get('alpha', 0),
                    metrics.get('market_return', 0),
                    metrics.get('hold_pct', 0),
                    metrics.get('entropy', 0),
                ])

        logging.info(f"    Benchmark saved: {filename}")


def main():
    parser = argparse.ArgumentParser(description='Dojo v3: Historical Data Training')
    parser.add_argument('--schedule', default='training_schedule.json',
                        help='Path to training schedule JSON')
    parser.add_argument('--checkpoint', default=None,
                        help='Starting checkpoint (default: poppy_v2_synthetic_complete)')
    parser.add_argument('--start-block', type=int, default=1,
                        help='Starting block number (1-based)')
    parser.add_argument('--max-blocks', type=int, default=None,
                        help='Maximum blocks to train (default: all)')
    parser.add_argument('--model-name', default=MODEL_NAME,
                        help='Model name')
    parser.add_argument('--model-version', default=MODEL_VERSION,
                        help='Model version')
    parser.add_argument('--epochs-per-block', type=int, default=60,
                        help='Epochs per checkpoint block')
    # TASK_064: Stratified training
    parser.add_argument('--stratified', action='store_true', default=False,
                        help='Enable stratified training: cycle through periods to prevent forgetting (TASK_064)')
    parser.add_argument('--periods-per-batch', type=int, default=4,
                        help='Number of periods to batch in stratified mode (default: 4)')
    parser.add_argument('--epochs-per-period', type=int, default=15,
                        help='Epochs per period before switching in stratified mode (default: 15)')
    # TASK_105: Loop mode
    parser.add_argument('--loop', action='store_true', default=False,
                        help='Infinite loop mode: cycle through periods until Ctrl+C (default: one-shot)')

    args = parser.parse_args()

    dojo = DojoV3Historical(
        schedule_path=args.schedule,
        model_name=args.model_name,
        model_version=args.model_version,
        epochs_per_block=args.epochs_per_block,
    )

    if args.stratified:
        # TASK_064: Stratified training - cycle through periods
        success = dojo.run_training_stratified(
            start_checkpoint=args.checkpoint,
            start_block=args.start_block,
            max_blocks=args.max_blocks,
            periods_per_batch=args.periods_per_batch,
            epochs_per_period=args.epochs_per_period,
            loop_mode=args.loop,
        )
    else:
        # Original sequential training
        success = dojo.run_training(
            start_checkpoint=args.checkpoint,
            start_block=args.start_block,
            max_blocks=args.max_blocks,
        )

    sys.exit(0 if success else 1)


